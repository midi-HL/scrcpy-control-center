void ContentPanel::renderVirtualDisplayPanel() {
    ImGui::Text(TR("menu_virtual_display"));
    ImGui::Separator();
    renderFeatureControls("virtual_display");

    ImGui::Spacing();
    ImGui::Separator();

    // Active instances info
    auto& pm = ProcessManager::instance();
    size_t active = pm.getActiveCount();

    ImGui::Text("Active scrcpy instances: %zu", active);
    if (active > 0) {
        ImGui::SameLine();
        if (ImGui::SmallButton("Stop All")) {
            pm.stopAll();
            LOG_INFO("All scrcpy instances stopped");
        }
    }

    ImGui::Spacing();

    // Quick launch section
    ImGui::Text("Quick Launch Virtual Display:");
    static char vdSizeBuf[64] = "1920x1080";
    static char vdAppBuf[128] = "";
    ImGui::InputText("Display Size", vdSizeBuf, sizeof(vdSizeBuf));
    ImGui::InputText("App Package (optional)", vdAppBuf, sizeof(vdAppBuf));

    auto& dm = DeviceManager::instance();
    std::string serial = dm.getSelectedSerial();

    if (serial.empty()) {
        ImGui::BeginDisabled();
    }
    if (ImGui::Button("Create Virtual Display", ImVec2(250, 0))) {
        std::vector<std::string> args;
        std::string displayArg = "--new-display";
        if (strlen(vdSizeBuf) > 0) {
            displayArg += "=" + std::string(vdSizeBuf);
        }
        args.push_back(displayArg);
        args.push_back("--flex-display");
        args.push_back("--no-vd-system-decorations");
        if (strlen(vdAppBuf) > 0) {
            args.push_back("--start-app=" + std::string(vdAppBuf));
        }

        auto& cfg = ConfigManager::instance().getSettings();
        if (pm.startScrcpy(cfg.scrcpyPath, args, serial)) {
            LOG_INFO("Virtual display created: %s", vdSizeBuf);
        }
    }
    if (serial.empty()) {
        ImGui::EndDisabled();
        ImGui::SameLine();
        ImGui::TextColored(ImVec4(1, 0.5f, 0.3f, 1), "(no device)");
    }
}

void ContentPanel::renderAppManagerPanel() {
    ImGui::Text(TR("menu_app_manager"));
    ImGui::Separator();

    auto& dm = DeviceManager::instance();
    auto& am = AppManager::instance();
    std::string serial = dm.getSelectedSerial();

    if (serial.empty()) {
        ImGui::TextColored(ImVec4(1, 0.5f, 0.3f, 1), "No device selected");
        ImGui::Text("Select a device in the Device tab first.");
        return;
    }

    // Refresh button
    if (am.isRefreshing()) {
        ImGui::Text("Refreshing...");
    } else {
        if (ImGui::Button("Refresh App List", ImVec2(200, 0))) {
            // Run refresh in background to avoid blocking UI
            std::thread([serial]() {
                AppManager::instance().refreshAppList(serial);
            }).detach();
        }
    }

    ImGui::Spacing();

    // App list
    auto apps = am.getApps();
    if (apps.empty()) {
        ImGui::TextDisabled("No apps loaded. Click 'Refresh App List' to scan device.");
        return;
    }

    ImGui::Text("Installed Apps (%zu):", apps.size());
    ImGui::SameLine();

    // Filter
    static char filterBuf[128] = "";
    ImGui::SetNextItemWidth(200);
    ImGui::InputTextWithHint("##app_filter", "Filter packages...", filterBuf, sizeof(filterBuf));

    ImGui::Spacing();

    // App table
    if (ImGui::BeginTable("AppTable", 4,
        ImGuiTableFlags_Borders | ImGuiTableFlags_RowBg | ImGuiTableFlags_ScrollY |
        ImGuiTableFlags_Resizable | ImGuiTableFlags_SizingStretchProp,
        ImVec2(0, 400))) {
        ImGui::TableSetupColumn("Package", ImGuiTableColumnFlags_WidthStretch);
        ImGui::TableSetupColumn("Status", ImGuiTableColumnFlags_WidthFixed, 60);
        ImGui::TableSetupColumn("Type", ImGuiTableColumnFlags_WidthFixed, 60);
        ImGui::TableSetupColumn("Actions", ImGuiTableColumnFlags_WidthFixed, 250);
        ImGui::TableHeadersRow();

        for (const auto& app : apps) {
            // Apply filter
            if (filterBuf[0] != '\0' &&
                app.packageName.find(filterBuf) == std::string::npos) {
                continue;
            }

            ImGui::TableNextRow();

            // Package name
            ImGui::TableNextColumn();
            ImGui::Text("%s", app.packageName.c_str());

            // Status
            ImGui::TableNextColumn();
            if (app.enabled) {
                ImGui::TextColored(ImVec4(0.3f, 1, 0.3f, 1), "Active");
            } else {
                ImGui::TextColored(ImVec4(0.6f, 0.6f, 0.6f, 1), "Frozen");
            }

            // Type
            ImGui::TableNextColumn();
            if (app.isSystem) {
                ImGui::TextColored(ImVec4(0.6f, 0.6f, 1, 1), "System");
            } else {
                ImGui::Text("User");
            }

            // Actions
            ImGui::TableNextColumn();
            ImGui::PushID(app.packageName.c_str());

            if (app.enabled) {
                // Freeze button
                if (ImGui::SmallButton("Freeze")) {
                    am.freezeApp(serial, app.packageName);
                }
                ImGui::SameLine();
            } else {
                // Unfreeze button
                if (ImGui::SmallButton("Unfreeze")) {
                    am.unfreezeApp(serial, app.packageName);
                }
                ImGui::SameLine();
            }

            // Launch button
            if (app.enabled && ImGui::SmallButton("Launch")) {
                am.launchApp(serial, app.packageName);
            }
            ImGui::SameLine();

            // Launch on VD button
            if (app.enabled && ImGui::SmallButton("Launch on VD")) {
                am.launchAppOnVirtualDisplay(serial, app.packageName);
            }

            ImGui::PopID();
        }
        ImGui::EndTable();
    }

    // Batch operations
    ImGui::Spacing();
    ImGui::Separator();
    ImGui::Text("Batch Operations:");
    if (ImGui::Button("Freeze All System Apps", ImVec2(200, 0))) {
        for (const auto& app : apps) {
            if (app.isSystem && app.enabled && !app.packageName.empty()) {
                am.freezeApp(serial, app.packageName);
            }
        }
    }
}

